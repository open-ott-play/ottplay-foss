"use strict";
// Generate qualified shared-core UA tables; no network or JS VM in native requests.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const { createHash } = require("node:crypto");

const args = process.argv.slice(2);
const check = args.includes("--check");
const rootAt = args.indexOf("--root");
const root =
    rootAt < 0 ? path.resolve(__dirname, "..") : path.resolve(args[rootAt + 1]);
assert(
    args.every(
        (arg, i) =>
            arg === "--check" ||
            arg === "--root" ||
            (rootAt >= 0 && i === rootAt + 1)
    ),
    "Usage: generate-m3u-user-agents.cjs [--check] [--root DIRECTORY]"
);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const manifest = JSON.parse(
    fs.readFileSync(
        path.join(root, "vendor/ottplay-core.manifest.json"),
        "utf8"
    )
);
assert.equal(manifest.schema, 1);
assert.equal(manifest.name, "ottplay-shared-core");
assert.match(manifest.source.sha256, /^[a-f0-9]{64}$/);
for (const name of ["ottplay-core.js", "ottplay-core.LICENSE.txt"]) {
    assert.equal(
        digest(fs.readFileSync(path.join(root, "vendor", name))),
        manifest.artifacts[name].sha256,
        "Unqualified vendor artifact: " + name
    );
}
const context = vm.createContext({ console });
vm.runInContext(
    fs.readFileSync(path.join(root, "vendor/ottplay-core.js"), "utf8"),
    context,
    { timeout: 10000 }
);
const core = context["play.ott:ottplay-shared-core"];
assert(core, "Qualified Core export is absent");
const presets = core.m3uUserAgentPresets();
const defaultUA = core.m3uDefaultUserAgent();
const entries = Object.entries(presets).sort(([a], [b]) =>
    a.localeCompare(b, "en")
);
assert(entries.length > 0);
assert.equal(typeof defaultUA, "string");
assert(
    defaultUA && !/[^\x20-\x7e]/.test(defaultUA),
    "Native preset literals must be printable ASCII"
);
for (const [key, ua] of entries) {
    assert.match(key, /^[a-z][a-z0-9_-]*$/);
    assert.equal(typeof ua, "string");
    assert(
        ua && !/[^\x20-\x7e]/.test(ua),
        "Native preset literals must be printable ASCII"
    );
    assert.equal(core.resolveM3uUserAgent(key), ua);
    assert.equal(core.resolveM3uUserAgent(key.toUpperCase()), ua);
}
for (const value of [null, undefined, ""])
    assert.equal(core.resolveM3uUserAgent(value), defaultUA);
for (const value of [
    " ",
    " Custom/1.0 ",
    "WebOS ",
    "constructor",
    "KODI",
    "TİZEN",
    "WEBOſ",
    "ẞ",
])
    assert.equal(core.resolveM3uUserAgent(value), value);
const begin = "// BEGIN GENERATED M3U USER AGENTS";
const end = "// END GENERATED M3U USER AGENTS";
const provenance = `// Core ${manifest.version}; source SHA256 ${manifest.source.sha256}; JS SHA256 ${manifest.artifacts["ottplay-core.js"].sha256}.`;
const quote = (value) => JSON.stringify(value);
const rust = [
    begin,
    "// Generated by scripts/generate-m3u-user-agents.cjs; do not edit this block.",
    provenance,
    `const DEFAULT_USER_AGENT: &str = ${quote(defaultUA)};`,
    "const UA_PRESETS: &[(&str, &str)] = &[",
    ...entries.map(([id, ua]) => `    (${quote(id)}, ${quote(ua)}),`),
    "];",
    "",
    "fn resolve_user_agent(input: &str) -> &str {",
    "    if input.is_empty() { return DEFAULT_USER_AGENT; }",
    "    UA_PRESETS.iter().find(|(key, _)| input.eq_ignore_ascii_case(key))",
    "        .map(|(_, ua)| *ua).unwrap_or(input)",
    "}",
    end,
].join("\n");
const swift = [
    begin,
    "// Generated by scripts/generate-m3u-user-agents.cjs; do not edit this block.",
    provenance,
    `private let defaultUserAgent = ${quote(defaultUA)}`,
    "private let uaPresets: [String: String] = [",
    ...entries.map(([id, ua]) => `  ${quote(id)}: ${quote(ua)},`),
    "]",
    "",
    "private func resolveUA(_ input: String?) -> String {",
    "  guard let input, !input.isEmpty else { return defaultUserAgent }",
    "  guard input.utf8.allSatisfy({ $0 < 128 }) else { return input }",
    "  return uaPresets[input.lowercased()] ?? input",
    "}",
    end,
].join("\n");
const esm = [
    "/** Generated by scripts/generate-m3u-user-agents.cjs from qualified shared Core exports. */",
    provenance,
    "export const UA_PRESETS: Record<string, string> = {",
    ...entries.map(([id, ua]) => `    ${id}: ${quote(ua)},`),
    "};",
    "",
    "export function resolveUA(input?: string): string {",
    `    if (!input) return ${quote(defaultUA)};`,
    "    if (/[^\\x00-\\x7f]/.test(input)) return input;",
    "    const key = input.toLowerCase();",
    "    return Object.prototype.hasOwnProperty.call(UA_PRESETS, key)",
    "        ? UA_PRESETS[key]",
    "        : input;",
    "}",
    "",
].join("\n");
function replaceBlock(source, generated, original) {
    const start = source.indexOf(begin);
    const finish = source.indexOf(end);
    if (start >= 0 || finish >= 0) {
        assert(start >= 0 && finish > start, "Malformed generated block");
        return (
            source.slice(0, start) +
            generated +
            source.slice(finish + end.length)
        );
    }
    assert(original.test(source), "Original UA definition not found");
    return source.replace(original, generated);
}
const outputs = new Map();
const rustFile = "src-rs/core/src/m3u.rs";
const swiftFile = "ios/App/App/M3UProxy.swift";
let rustSource = replaceBlock(
    fs.readFileSync(path.join(root, rustFile), "utf8"),
    rust,
    /\/\/\/ UA presets mirrored from server\.py\nconst UA_PRESETS:[\s\S]*?\n\];/
);
const legacyResolver =
    /    let ua = if params\.ua\.is_empty\(\) \{[\s\S]*?\n    \};/;
if (legacyResolver.test(rustSource))
    rustSource = rustSource.replace(
        legacyResolver,
        "    let ua = resolve_user_agent(&params.ua);"
    );
// Preserve transport ownership and avoid an extra string allocation at each request.
rustSource = rustSource.replace(
    "super::proxy::fetch(&url, &ua).await",
    "super::proxy::fetch(&url, ua).await"
);
assert(
    rustSource.includes("let ua = resolve_user_agent(&params.ua);"),
    "Native Rust proxy must use the generated resolver"
);
outputs.set(rustFile, rustSource);
outputs.set(
    swiftFile,
    replaceBlock(
        fs.readFileSync(path.join(root, swiftFile), "utf8"),
        swift,
        /\/\/ UA presets mirrored from src-rs\/core\/src\/m3u\.rs and archive\/server\.py\n[\s\S]*?\nprivate func resolveUA\(_ input: String\?\) -> String \{[\s\S]*?\n\}/
    )
);
outputs.set("src/plugins/m3u-user-agent.ts", esm);
for (const [file, expected] of outputs) {
    if (check)
        assert.equal(
            fs.readFileSync(path.join(root, file), "utf8"),
            expected,
            "Stale generated Core UA policy: " + file
        );
    else fs.writeFileSync(path.join(root, file), expected);
}
console.log(
    (check ? "PASS qualified generated" : "Updated qualified generated") +
        " M3U user agents: Rust, Swift, optional ESM"
);
