#!/usr/bin/env python3
"""Generate the Unicode 17 tables for the versioned archive search predicate."""
from pathlib import Path
import unicodedata

if unicodedata.unidata_version != "17.0.0":
    raise SystemExit("Generation requires Python with Unicode 17.0.0")

def ranges(predicate):
    result, start = [], None
    for code in range(0x110001):
        accepted = code < 0x110000 and predicate(chr(code))
        if accepted and start is None:
            start = code
        elif not accepted and start is not None:
            result.append((start, code - 1))
            start = None
    return result

lines = ["// Generated by scripts/generate-epg-unicode.py using Unicode 17.0.0.",
         "// Archive profile: nfkc-casefold-words-u17-v1. Do not edit manually."]
for name, predicate in [("ALNUM", str.isalnum), ("CONTROL", lambda ch: unicodedata.category(ch).startswith("C"))]:
    lines.append("pub(super) const " + name + ": &[(u32, u32)] = &[")
    lines.extend(f"    (0x{start:x}, 0x{end:x})," for start, end in ranges(predicate))
    lines.append("];")
lines.append("pub(super) const FOLD: &[(u32, &str)] = &[")
for code in range(0x110000):
    char = chr(code)
    folded = char.casefold()
    if char != folded:
        literal = "".join("\\u{" + format(ord(ch), "x") + "}" for ch in folded)
        lines.append(f'    (0x{code:x}, "{literal}"),')
lines.append("];")
output = Path(__file__).resolve().parents[1] / "src-rs/server/src/hosted_epg/unicode17.rs"
output.write_text("\n".join(lines) + "\n")
